package tn.fst.spring.netvoyage.dtos;


public class InvitationItem {
    private String nom;
    private String email;

    // Getters and setters
    public String getNom() {
        return nom;
    }

    public void setNom(String nom) {
        this.nom = nom;
    }

    public String getEmail() {
        return email;
    }

    public void setEmail(String email) {
        this.email = email;
    }
}